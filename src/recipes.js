// 名称归一化：去掉空格/括号/标点并转小写，便于和 AI 生成的菜名做模糊匹配。
const norm = (s = "") =>
  String(s).replace(/[\s（）()【】\[\]{}·•・\-—_、,，。.!！?？:：;；'"“”]/g, "").toLowerCase();

const INDEX = Object.keys(RECIPES).reduce((m, k) => { m[norm(k)] = k; return m; }, {});

// 查找做法：精确（归一化后）→ 互相包含匹配。找不到返回 null。
export function lookupRecipe(name) {
  if (!name) return null;
  const key = norm(name);
  if (!key) return null;
  if (INDEX[key]) return RECIPES[INDEX[key]];
  const hit = Object.keys(INDEX).find(k => k.includes(key) || key.includes(k));
  return hit ? RECIPES[INDEX[hit]] : null;
}

